/**
 * Generates src/data/europeDots.ts — a dot-grid of the 15 swelt delivery
 * countries used as "city lights" on the night-style dropshipping map
 * (DropshipFlowMap). Projection mirrors generate-europe-map-paths.mjs,
 * so dots align exactly with the country outlines.
 *
 * Usage:  node scripts/generate-europe-dots.mjs [path/to/europe.geojson]
 */
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const GEO_URL = 'https://cdn.jsdelivr.net/gh/leakyMirror/map-of-europe@master/GeoJSON/europe.geojson';

const DELIVERY = new Set(['CZ', 'SK', 'AT', 'DE', 'PL', 'HU', 'RO', 'BG', 'HR', 'SI', 'BA', 'RS', 'GR', 'IT', 'FR']);
const NAME_TO_ISO = {
  'Czech Republic': 'CZ', 'Czechia': 'CZ', 'Slovakia': 'SK', 'Austria': 'AT',
  'Germany': 'DE', 'Poland': 'PL', 'Hungary': 'HU', 'Romania': 'RO',
  'Bulgaria': 'BG', 'Croatia': 'HR', 'Slovenia': 'SI', 'Greece': 'GR',
  'Italy': 'IT', 'France': 'FR', 'Serbia': 'RS', 'Republic of Serbia': 'RS',
  'Bosnia and Herzegovina': 'BA',
};

const W = 800;
const PAD = 14;
const SPACING = 6.5;
const mercY = (lat) => Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360));
const invMercY = (my) => ((2 * Math.atan(Math.exp(my)) - Math.PI / 2) * 180) / Math.PI;

function getIso(f) {
  const p = f.properties || {};
  const raw = (p.ISO2 || p.iso_a2 || p.ISO_A2 || '').toString().toUpperCase();
  if (raw && raw !== '-99') return raw;
  return NAME_TO_ISO[p.NAME || p.name || ''] || '';
}
function polygons(g) {
  if (!g) return [];
  if (g.type === 'Polygon') return [g.coordinates];
  if (g.type === 'MultiPolygon') return g.coordinates;
  return [];
}
function inRing(lon, lat, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}
function inPolygon(lon, lat, poly) {
  if (!inRing(lon, lat, poly[0])) return false;
  for (let h = 1; h < poly.length; h++) if (inRing(lon, lat, poly[h])) return false;
  return true;
}

async function loadGeo() {
  const arg = process.argv[2];
  if (arg) return JSON.parse(readFileSync(arg, 'utf8'));
  const res = await fetch(GEO_URL);
  if (!res.ok) throw new Error(`GeoJSON fetch failed: ${res.status}`);
  return res.json();
}

const data = await loadGeo();
const features = data.features.filter((f) => DELIVERY.has(getIso(f)));

let lonMin = Infinity, lonMax = -Infinity, latMin = Infinity, latMax = -Infinity;
for (const f of features) {
  for (const poly of polygons(f.geometry)) {
    for (const ring of poly) {
      for (const [lon, lat] of ring) {
        if (lon < lonMin) lonMin = lon;
        if (lon > lonMax) lonMax = lon;
        if (lat < latMin) latMin = lat;
        if (lat > latMax) latMax = lat;
      }
    }
  }
}
const lonSpan = ((lonMax - lonMin) * Math.PI) / 180;
const myMax = mercY(latMax);
const mySpan = myMax - mercY(latMin);
const H = Math.round(W * (mySpan / lonSpan));

const unproject = (x, y) => {
  const lon = ((x - PAD) / (W - PAD * 2)) * (lonMax - lonMin) + lonMin;
  const my = myMax - ((y - PAD) / (H - PAD * 2)) * mySpan;
  return [lon, invMercY(my)];
};

const countryDots = {};
let total = 0;
for (let row = 0, y = PAD; y <= H - PAD; y += SPACING, row++) {
  const xOffset = row % 2 === 0 ? 0 : SPACING / 2;
  for (let x = PAD + xOffset; x <= W - PAD; x += SPACING) {
    const [lon, lat] = unproject(x, y);
    for (const f of features) {
      let hit = false;
      for (const poly of polygons(f.geometry)) {
        if (inPolygon(lon, lat, poly)) { hit = true; break; }
      }
      if (hit) {
        (countryDots[getIso(f)] ||= []).push([Math.round(x), Math.round(y)]);
        total++;
        break;
      }
    }
  }
}

const lines = [];
lines.push('/**');
lines.push(' * AUTO-GENERATED by scripts/generate-europe-dots.mjs — do not edit by hand.');
lines.push(' * City-light dot grid of the 15 swelt delivery countries; projection');
lines.push(' * matches europeMapPaths.ts, so dots align with country outlines.');
lines.push(' */');
lines.push('export const COUNTRY_DOTS: Record<string, [number, number][]> = {');
for (const [iso, dots] of Object.entries(countryDots)) {
  lines.push(`  ${iso}: ${JSON.stringify(dots)},`);
}
lines.push('};');
lines.push('');

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = join(__dirname, '..', 'src', 'data', 'europeDots.ts');
writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`Wrote ${outPath}: ${total} dots, ${W}x${H}`);
